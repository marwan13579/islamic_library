/**
 * يدمج الدروس الإضافية والتعديلات في قائمة الدروس الأساسية.
 * التعديلات تضيف كتل `evidence` فقط، فلا تمسّ نصّ درس مولَّد.
 * @param {Array<object>} base
 * @returns {Array<object>}
 */
export function mergeLessons(base) {
  const patched = base.map((lesson) => {
    const add = LESSON_PATCHES[lesson.id];
    if (!add?.length) return lesson;
    return { ...lesson, body: [...add, ...(lesson.body ?? [])] };
  });
  return [...patched, ...EXTRA_LESSONS];
}

/**
 * يبني فهرس المعرّف إلى الدرس.
 * @param {Array<object>} list
 * @returns {Record<string, object>}
 */
export function buildLessonIndex(list) {
  /** @type {Record<string, object>} */
  const index = {};
  for (const lesson of list) index[lesson.id] = lesson;
  return index;
}
