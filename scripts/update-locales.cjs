const dirs = fs.readdirSync(LOCALES_DIR).filter(f => fs.statSync(path.join(LOCALES_DIR, f)).isDirectory());

dirs.forEach(dir => {
  const file = path.join(LOCALES_DIR, dir, 'common.json');
  let data = {};
  try {
    data = JSON.parse(fs.readFileSync(file, 'utf8'));
  } catch (e) {
    data = {};
  }
  if (!data.common) data.common = {};

  Object.entries(uiKeys).forEach(([k, v]) => {
    if (data.common[k] === undefined) data.common[k] = v;
  });

  if (data.common.cats === undefined) data.common.cats = { ...cats };
  if (data.common.catBlurb === undefined) data.common.catBlurb = { ...catBlurb };

  if (data.common.tools === undefined) {
    if (dir === 'ar') {
      data.common.tools = {};
    } else {
      data.common.tools = {};
      Object.entries(tools).forEach(([k, [name, desc]]) => {
        data.common.tools[k] = [name, desc];
      });
    }
  }

  fs.writeFileSync(file, JSON.stringify(data, null, 2) + '\n');
  console.log(`Updated ${file}`);
});

